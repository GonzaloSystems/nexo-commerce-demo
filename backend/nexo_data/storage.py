import copy
import json
from pathlib import Path
import sqlite3
from .config import STATE_DIR
from .normalize import utc_now

class Store:
    def __init__(self,path=None):
        self.path=Path(path) if path else STATE_DIR/'nexo.sqlite3'
        self.path.parent.mkdir(parents=True,exist_ok=True,mode=0o700)
        with self.connect() as db:
            db.executescript('''
              PRAGMA journal_mode=WAL;
              CREATE TABLE IF NOT EXISTS snapshots(
                provider TEXT, asin TEXT, queried_at TEXT, payload TEXT NOT NULL,
                PRIMARY KEY(provider,asin,queried_at));
              CREATE TABLE IF NOT EXISTS events(
                provider TEXT, asin TEXT, metric TEXT, category TEXT, at TEXT,
                value REAL, state TEXT, provider_value REAL,
                PRIMARY KEY(provider,asin,metric,category,at));
              CREATE INDEX IF NOT EXISTS event_window ON events(asin,metric,category,at);
              CREATE TABLE IF NOT EXISTS runs(
                id INTEGER PRIMARY KEY, provider TEXT, at TEXT, status TEXT,
                product_count INTEGER, meta TEXT);
            ''')
        self.path.chmod(0o600)

    def connect(self):
        db=sqlite3.connect(self.path,timeout=10)
        db.row_factory=sqlite3.Row
        return db

    def save(self,record):
        source,asin,stamp=record['provider'],record['asin'],record['queried_at']
        rows=[]
        def add(metric,category,series):
            for e in series:rows.append((source,asin,metric,category,e['at'],e['value'],e['state'],e.get('provider_value')))
        for cat,series in record['rank_history_by_category'].items():add('rank',cat,series)
        for kind,series in record['price_history'].items():add('price:'+kind,'',series)
        add('offer_count_new','',record['offer_count_history'])
        add('monthly_units_min','',record['monthly_units_min_history'])
        if record['price_current'] is not None and record['price_observed_at']:
            add('price:'+str(record['price_kind']),'',[{'at':record['price_observed_at'],'value':record['price_current'],'state':'observed'}])
        if record['monthly_units_min'] is not None and record['monthly_units_observed_at']:
            add('monthly_units_min','',[{'at':record['monthly_units_observed_at'],'value':record['monthly_units_min'],'state':'observed'}])
        with self.connect() as db:
            db.execute('INSERT OR REPLACE INTO snapshots VALUES(?,?,?,?)',(source,asin,stamp,json.dumps(record,ensure_ascii=False,allow_nan=False)))
            db.executemany('INSERT OR REPLACE INTO events VALUES(?,?,?,?,?,?,?,?)',rows)

    def record_run(self,provider,status,count=0,meta=None):
        # Metadata is a whitelist generated by the orchestrator, never a URL,
        # access token, raw provider error or credentials dictionary.
        with self.connect() as db:
            db.execute('INSERT INTO runs(provider,at,status,product_count,meta) VALUES(?,?,?,?,?)',
                       (provider,utc_now(),status,count,json.dumps(meta or {})))

    def status(self):
        with self.connect() as db:
            rows=db.execute('SELECT * FROM runs WHERE id IN (SELECT max(id) FROM runs GROUP BY provider)').fetchall()
            count=db.execute('SELECT count(DISTINCT asin) AS n FROM snapshots').fetchone()['n']
        return {'product_count':count,'last_runs':[dict(r) for r in rows]}

    def records(self):
        with self.connect() as db:
            rows=db.execute('''SELECT s.payload FROM snapshots s JOIN
              (SELECT provider,asin,max(queried_at) AS q FROM snapshots GROUP BY provider,asin) t
              ON s.provider=t.provider AND s.asin=t.asin AND s.queried_at=t.q''').fetchall()
        return [json.loads(r['payload']) for r in rows]

    def products(self):
        groups={}
        for r in self.records():groups.setdefault(r['asin'],{})[r['provider']]=r
        result=[]
        for asin,providers in groups.items():
            primary=providers.get('sp-api') or providers.get('keepa')
            r=copy.deepcopy(primary)
            keepa=providers.get('keepa')
            sources={k:{'queried_at':v['queried_at'],'provider_updated_at':v['provider_updated_at']} for k,v in providers.items()}
            r['api_sources']=sources
            r['field_sources']={k:r['provider'] for k in ['title','parent_asin','rank_current','price_current','seller_count_observed']}
            if keepa and r['provider']!='keepa':
                for field in ['title','brand','color','image_url','parent_asin','category_tree','variations','child_asins']:
                    if not r.get(field):r[field]=copy.deepcopy(keepa[field])
                for fields in [('price_current','price_kind','price_observed_at','availability'),
                               ('rank_current','rank_category_id','rank_category_name','rank_observed_at')]:
                    if r[fields[0]] is None:
                        for f in fields:r[f]=copy.deepcopy(keepa[f])
                        r['field_sources'][fields[0]]='keepa'
                for f in ['rank_history_by_category','price_history','offer_count_history','monthly_units_min_history',
                          'monthly_units_min','monthly_units_scope','monthly_units_observed_at']:
                    r[f]=copy.deepcopy(keepa[f])
                if keepa['seller_count_observed'] is not None:
                    for f in ['seller_count_observed','seller_count_scope']:r[f]=keepa[f]
                    r['field_sources']['seller_count_observed']='keepa'
                r['quality_warnings']=sorted(set(r['quality_warnings']+keepa['quality_warnings']))
            result.append(r)
        return sorted(result,key=lambda r:r['asin'])

    def history(self,asin,metric,category='',provider='keepa'):
        with self.connect() as db:
            rows=db.execute('SELECT at,value,state,provider_value FROM events WHERE provider=? AND asin=? AND metric=? AND category=? ORDER BY at',
                            (provider,asin,metric,category)).fetchall()
        return [dict(r) for r in rows]
